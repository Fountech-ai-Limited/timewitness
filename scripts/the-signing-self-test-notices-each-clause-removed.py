"""Say whether the signing route's two self-tests notice each of their clauses taken away.

`scripts/the-binaries-are-signed.py --self-test` stands between a change to the signature check and
a release that trusts it, and `scripts/the-release-route-holds.py --self-test` between a change to the
route check and a setting that moves unnoticed. A self-test that stays green with a clause deleted is
not holding that clause, and nothing else would notice until a binary signed by somebody else passed
or the route widened. So this copies both checks, with the workflows the route check reads, to a
scratch folder, removes one clause at a time, and runs the self-test of the check it was removed
from on each copy. Every copy must fail it.

    python scripts/the-signing-self-test-notices-each-clause-removed.py

Each clause is named by the exact text it is removed from. Where that text is not in the check
exactly once, the clause is reported as MOVED and the run fails, because a clause that has been
rewritten is a clause nobody has shown the self-test holds. Fix the text here in the same change.
Where a clause is a call in the route check's `run()`, taking it away means the call is never made,
which is how a check stops checking without any judgement in it changing.

It prints a line per clause, CAUGHT, MISSED, CRASHED or MOVED, and exits 0 only when both untouched checks
pass their self-tests and every clause is CAUGHT. The copies run a few at a time, as many as
`TW_CLAUSE_WORKERS` says and four where it says nothing.
"""

