CHECKS = [
    (SIGNATURE_CHECK, ["--self-test"], SIGNATURE_CLAUSES),
    (ROUTE_CHECK, ["--self-test", "--need-yaml"], ROUTE_CLAUSES),
]


def self_test(root, check, flags):
    done = subprocess.run([sys.executable, os.path.join(root, "scripts", check)] + flags,
                          capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=900)
    return done.returncode, (done.stdout or "") + (done.stderr or "")


def workers():
    try:
        return max(1, int(os.environ.get("TW_CLAUSE_WORKERS", "4")))
    except ValueError:
        return 4


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else HERE
    root = os.path.dirname(os.path.abspath(source))
    work = tempfile.mkdtemp(prefix="tw-clauses-")
    failed = False
    try:
        # Both checks, the identities and fixtures, and the workflows, which is all either self-test reads.
        base = os.path.join(work, "base")
        os.makedirs(os.path.join(base, "scripts"))
        for name in (SIGNATURE_CHECK, ROUTE_CHECK, "signing-identities.json"):
            shutil.copy(os.path.join(source, name), os.path.join(base, "scripts"))
        shutil.copytree(os.path.join(source, "signing-fixtures"), os.path.join(base, "scripts", "signing-fixtures"))
        shutil.copytree(os.path.join(root, ".github", "workflows"), os.path.join(base, ".github", "workflows"))

        for check, flags, _ in CHECKS:
            code, out = self_test(base, check, flags)
            if code != 0:
                print("FAIL: the untouched %s does not pass its own self-test, so nothing below means anything" % check)
                print(out.strip())
                return 1
            print("PASS: the untouched %s passes its own self-test" % check)

        jobs = []
        for check, flags, clauses in CHECKS:
            with open(os.path.join(source, check), encoding="utf-8") as f:
                text = f.read()
            for clause in clauses:
                name, pairs = clause[0], list(zip(clause[1::2], clause[2::2]))
                if any(text.count(old) != 1 for old, _ in pairs):
                    jobs.append((check, name, None))
                    continue
                changed = text
                for old, new in pairs:
                    changed = changed.replace(old, new)
                folder = os.path.join(work, "clause-%d" % len(jobs))
                shutil.copytree(base, folder)
                with open(os.path.join(folder, "scripts", check), "w", encoding="utf-8", newline="\n") as f:
                    f.write(changed)
                jobs.append((check, name, (folder, flags)))

        def judged(job):
            check, name, copy = job
            if copy is None:
                return "MOVED: %s: %s: the text it lives in is not in the check exactly once" % (check, name)
            code, out = self_test(copy[0], check, copy[1])
            # A self-test that dies has judged nothing, and a later change that caught what killed
            # it would turn it green; so only a self-test that ran to its end and failed counts.
            if "Traceback (most recent call last)" in out:
                return "CRASHED: %s: %s: the self-test died rather than judging: %s" % (
                    check, name, out.strip().splitlines()[-1][:200])
            if code != 0:
                return "CAUGHT: %s: %s: the self-test fails without it" % (check, name)
            return "MISSED: %s: %s: the self-test passes without it" % (check, name)

        with concurrent.futures.ThreadPoolExecutor(max_workers=workers()) as pool:
            for line in pool.map(judged, jobs):
                print(line, flush=True)
                if not line.startswith("CAUGHT"):
                    failed = True
    finally:
        shutil.rmtree(work, ignore_errors=True)
    total = sum(len(clauses) for _, _, clauses in CHECKS)
    if failed:
        print("FAIL: the self-tests do not hold every clause of the signing route's two checks")
        return 1
    print("PASS: each self-test fails with any one of its clauses taken away, %d clauses across the two checks" % total)
    return 0


if __name__ == "__main__":
    sys.exit(main())
